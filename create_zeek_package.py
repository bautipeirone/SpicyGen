ZEEK_INTEGRATION_PROMPT_PATH = Path(__file__).parent / "prompts" / "zeek" / "INTEGRATION.md"

ZEEK_GENERATION_SYSTEM_PROMPT_TEMPLATE = """You are an expert Zeek + Spicy plugin author.

Use the following guide as the source of truth for syntax, structure, examples,
and common pitfalls.

{integration_instructions}

Given a Spicy parser and package metadata, produce three Zeek integration files.

Output must be valid JSON only. Do not wrap it in Markdown fences. The JSON
object must have exactly these string keys:
- "evt": the analyzer/<analyzer>.evt file content
- "zeek_spicy": the analyzer/zeek_<analyzer>.spicy file content
- "main_zeek": the scripts/main.zeek file content

- Do not include explanations or extra keys.
"""


def load_zeek_integration_instructions(path: Path = ZEEK_INTEGRATION_PROMPT_PATH) -> str:
    """Load the Zeek integration instructions used as prompt context."""
    try:
        return path.read_text()
    except OSError as exc:
        raise RuntimeError(f"Unable to read Zeek integration prompt from {path}: {exc}") from exc


def build_zeek_system_prompt(instructions: str) -> str:
    """Build the full system prompt from the reusable integration guide."""
    return ZEEK_GENERATION_SYSTEM_PROMPT_TEMPLATE.format(
        integration_instructions=instructions.strip()
    )


def format_files_for_feedback(files: ZeekIntegrationFiles) -> str:
    """Render generated files for a retry prompt."""
    return (
        "Previous generated files:\n\n"
        "evt:\n"
        "```spicy\n"
        f"{files.evt}"
        "```\n\n"
        "zeek_spicy:\n"
        "```spicy\n"
        f"{files.zeek_spicy}"
        "```\n\n"
        "main_zeek:\n"
        "```zeek\n"
        f"{files.main_zeek}"
        "```\n"
    )


def build_zeek_generation_prompt(
    *,
    spicy_source: str,
    module_name: str,
    analyzer_name: str,
    entry_unit: str,
    transports: list[str],
    compile_errors: str | None = None,
    previous_files: ZeekIntegrationFiles | None = None,
    response_error: str | None = None,
    previous_response: str | None = None,
) -> str:
    """Build the user prompt for the Zeek integration generation step."""
    prompt = (
        "Generate Zeek integration files for the following Spicy parser.\n\n"
        "CONSTRAINTS (follow exactly):\n"
        f"- The parser module is: {module_name}\n"
        f"- The Zeek integration module MUST be: Zeek_{analyzer_name}\n"
        f"- The analyzers name in .evt MUST start with: {analyzer_name}\n"
        f"- Transports: {[ transport.upper() for transport in transports ]}\n"
        f"- The .evt MUST import both {module_name} and Zeek_{analyzer_name}\n"
        f"- Entry unit: {module_name}::{entry_unit}\n"
        f"- In main.zeek, the Zeek module MUST be: {analyzer_name}\n"
        f"- Write analyzer/{analyzer_name.lower()}.evt content in the JSON key \"evt\"\n"
        f"- Write analyzer/zeek_{analyzer_name.lower()}.spicy content in the JSON key \"zeek_spicy\"\n"
        "- Write scripts/main.zeek content in the JSON key \"main_zeek\"\n\n"
    )

    if response_error:
        prompt += (
            "Your previous response could not be parsed as the required JSON bundle.\n"
            f"Parser error:\n{response_error}\n\n"
        )
        if previous_response:
            prompt += f"Previous raw response:\n{previous_response}\n\n"

    if compile_errors:
        prompt += (
            "The previous generated files failed `spicyz` compilation. "
            "Fix the files and return a complete replacement JSON bundle.\n\n"
            f"Compiler output:\n{compile_errors}\n\n"
        )
        if previous_files:
            prompt += format_files_for_feedback(previous_files) + "\n"

    prompt += f"PARSER SOURCE:\n```spicy\n{spicy_source}\n```"
    return prompt


def strip_json_code_fence(response: str) -> str:
    """Remove a single Markdown code fence around a JSON response if present."""
    cleaned = response.strip()
    match = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", cleaned, re.DOTALL)
    if match:
        return match.group(1).strip()
    return cleaned


def parse_llm_bundle(response: str) -> ZeekIntegrationFiles:
    """Parse the LLM JSON response containing the generated Zeek files."""
    cleaned = strip_json_code_fence(response)
    payload = None

    try:
        payload = json.loads(cleaned)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", cleaned, re.DOTALL)
        if not match:
            raise ValueError("LLM response did not contain a JSON object.")
        try:
            payload = json.loads(match.group(0))
        except json.JSONDecodeError as exc:
            raise ValueError(f"LLM response was not valid JSON: {exc}") from exc

    if not isinstance(payload, dict):
        raise ValueError("LLM response JSON must be an object.")

    required_keys = ("evt", "zeek_spicy", "main_zeek")
    missing = [key for key in required_keys if key not in payload]
    if missing:
        raise ValueError(f"LLM response missing required keys: {', '.join(missing)}")

    for key in required_keys:
        if not isinstance(payload[key], str) or not payload[key].strip():
            raise ValueError(f"LLM response key '{key}' must be a non-empty string.")

    return ZeekIntegrationFiles(
        evt=payload["evt"].strip() + "\n",
        zeek_spicy=payload["zeek_spicy"].strip() + "\n",
        main_zeek=payload["main_zeek"].strip() + "\n",
    )


def try_compile_zeek_files(
    *,
    spicy_info: SpicyParserInfo,
    analyzer_name: str,
    files: ZeekIntegrationFiles,
    spicyz_bin: str = "spicyz",
) -> str | None:
    """Compile generated Zeek integration files with spicyz.

    Returns None on success, otherwise a formatted compiler error string.
    """
    spicyz_path = shutil.which(spicyz_bin)
    if spicyz_path is None:
        raise RuntimeError(
            f"'{spicyz_bin}' not found on PATH. Install Spicy/Zeek tooling or use "
            "--skip-zeek-compile-check to generate without the refinement loop."
        )

    with tempfile.TemporaryDirectory(prefix="zeek-integration-") as tmp:
        tmp_dir = Path(tmp)
        parser_path = tmp_dir / spicy_info.source_path.name
        evt_path = tmp_dir / f"{analyzer_name.lower()}.evt"
        zeek_spicy_path = tmp_dir / f"zeek_{analyzer_name.lower()}.spicy"
        output_path = tmp_dir / f"{analyzer_name.lower()}.hlto"

        shutil.copy2(spicy_info.source_path, parser_path)
        evt_path.write_text(files.evt)
        zeek_spicy_path.write_text(files.zeek_spicy)

        result = subprocess.run(
            [
                spicyz_path,
                "-o",
                str(output_path),
                str(parser_path),
                str(zeek_spicy_path),
                str(evt_path),
            ],
            cwd=tmp_dir,
            capture_output=True,
            text=True,
        )

    if result.returncode == 0:
        return None

    return (
        f"spicyz exited with {result.returncode}\n"
        f"stdout:\n{result.stdout}\n"
        f"stderr:\n{result.stderr}"
    )


def summarize_usage_records(usage_records: list[dict | None]) -> dict | None:
    """Keep retry usage visible without assuming provider-specific schemas."""
    compact = [
        {"attempt": idx, "usage": usage}
        for idx, usage in enumerate(usage_records, start=1)
        if usage is not None
    ]
    if not compact:
        return None
    return {"attempts": compact}


def generate_zeek_files_with_llm(
    *,
    spicy_info: SpicyParserInfo,
    analyzer_name: str,
    metadata: ProtocolMetadata,
    model: str,
    config_path: Path | None,
    max_retries: int = 5,
    compile_check: bool = True,
    instructions_path: Path = ZEEK_INTEGRATION_PROMPT_PATH,
) -> tuple[ZeekIntegrationFiles, dict | None]:
    """Generate Zeek integration files by prompting and validating with spicyz."""
    if max_retries < 1:
        raise ValueError("max_retries must be at least 1")

    llm_params, _ = read_config(config_path)
    llm_config = get_autogen_config(model, llm_params)
    spicy_source = spicy_info.source_path.read_text()
    system_prompt = build_zeek_system_prompt(
        load_zeek_integration_instructions(instructions_path)
    )
    user_message = build_zeek_generation_prompt(
        spicy_source=spicy_source,
        module_name=spicy_info.module_name,
        analyzer_name=analyzer_name,
        entry_unit=spicy_info.entry_unit,
        transports=metadata.transports
    )

    usage_records: list[dict | None] = []
    last_files: ZeekIntegrationFiles | None = None
    last_error: str | None = None

    for attempt in range(1, max_retries + 1):
        logger.info("LLM attempt %s/%s", attempt, max_retries)
        response, usage = query_llm_once(
            llm_config=llm_config,
            system_prompt=system_prompt,
            user_message=user_message,
        )
        usage_records.append(usage)

        try:
            files = parse_llm_bundle(response)
        except ValueError as exc:
            last_error = str(exc)
            if attempt == max_retries:
                raise

            user_message = build_zeek_generation_prompt(
                spicy_source=spicy_source,
                module_name=spicy_info.module_name,
                analyzer_name=analyzer_name,
                entry_unit=spicy_info.entry_unit,
                transports=metadata.transports,
                response_error=last_error,
                previous_response=response,
            )
            continue

        last_files = files
        if not compile_check:
            return files, summarize_usage_records(usage_records)

        compile_errors = try_compile_zeek_files(
            spicy_info=spicy_info,
            analyzer_name=analyzer_name,
            files=files,
        )
        if compile_errors is None:
            logger.info("spicyz compilation succeeded")
            return files, summarize_usage_records(usage_records)

        last_error = compile_errors
        logger.warning("spicyz compilation failed; feeding errors back to the LLM")
        logger.debug("spicyz compilation errors:\n%s", compile_errors)
        if attempt < max_retries:
            user_message = build_zeek_generation_prompt(
                spicy_source=spicy_source,
                module_name=spicy_info.module_name,
                analyzer_name=analyzer_name,
                entry_unit=spicy_info.entry_unit,
                transports=metadata.transports,
                compile_errors=compile_errors,
                previous_files=files,
            )

    if last_files is None:
        raise RuntimeError(f"LLM did not produce valid Zeek files: {last_error}")

    logger.warning("Returning last generated files after exhausting spicyz retries")
    return last_files, summarize_usage_records(usage_records)


def generate_protocol_signatures(analyzer_name: str, metadata: ProtocolMetadata) -> str:
    signatures = ""
    for transport in metadata.transports:
        transport_signature = (
            f"signature dpd_{analyzer_name.lower()}_{transport.lower()} {{\n"
            f"  ip-proto == {transport}\n"
            f"{f'  dst-port == {metadata.port}\n' if metadata.port else ''}"
            f"  event \"{analyzer_name}_{transport.upper()} signature matched\"\n"
            f"  enable \"{analyzer_name}_{transport.upper()}\"\n"
            "}\n"
        )
        signatures += transport_signature

    return signatures


