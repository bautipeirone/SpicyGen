import re
import os
from pathlib import Path

MAIN_WRAPPER_SRC = r"""
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

#include "{wrapper_header_path}"

int main(int argc, char *argv[]) {{
    if (argc != 2) {{
        fprintf(stderr, "Usage: %s <binary_file>\n", argv[0]);
        return EXIT_FAILURE;
    }}

    const char *filename = argv[1];
    FILE *file = fopen(filename, "rb");
    if (!file) {{
        perror("Error opening file");
        return EXIT_FAILURE;
    }}

    // Determine the size of the file
    if (fseek(file, 0, SEEK_END) != 0) {{
        perror("Error seeking to end of file");
        fclose(file);
        return EXIT_FAILURE;
    }}
    
    long file_size_long = ftell(file);
    if (file_size_long < 0) {{
        perror("Error determining file size");
        fclose(file);
        return EXIT_FAILURE;
    }}
    fseek(file, 0, SEEK_SET);

    // EverParse typically uses 32-bit integers for buffer lengths
    if (file_size_long > UINT32_MAX) {{
        fprintf(stderr, "Error: File size exceeds maximum supported buffer length (4GB).\n");
        fclose(file);
        return EXIT_FAILURE;
    }}
    uint32_t file_size = (uint32_t)file_size_long;

    // Allocate memory for the file contents
    uint8_t *buffer = (uint8_t *)malloc(file_size);
    if (!buffer && file_size > 0) {{
        perror("Error allocating memory");
        fclose(file);
        return EXIT_FAILURE;
    }}

    // Read the binary data into the buffer
    size_t bytes_read = fread(buffer, 1, file_size, file);
    if (bytes_read != (size_t)file_size) {{
        fprintf(stderr, "Error: Incomplete read of the binary file.\n");
        free(buffer);
        fclose(file);
        return EXIT_FAILURE;
    }}

    fclose(file);

    bool is_valid = {parser_entrypoint}(buffer, file_size);

    if (is_valid) {{
        printf("Validation successful: The binary payload conforms to the specification.\n");
    }} else {{
        printf("Validation failed: The binary payload is invalid.\n");
    }}

    free(buffer);
    
    return is_valid ? EXIT_SUCCESS : EXIT_FAILURE;
}}
"""

ERROR_HANDLER_SRC = r"""
#include <stdio.h>

/*
* EverParse error callback. Automatically generated by the 3D runtime.
* The function name must exactly match what the generated code expects.
*/
void {callback_name}(const char *struct_name, const char *field_name, const char *reason) {{
    fprintf(stderr, "EverParse Validation Error in %s.%s: %s\n",
            struct_name ? struct_name : "UNKNOWN_STRUCT",
            field_name ? field_name : "UNKNOWN_FIELD",
            reason ? reason : "Unknown reason");
}}
"""

def normalize_identifier(entrypoint: str) -> str:
    return "".join([ w.capitalize() for w in entrypoint.split('_') ])

def get_main_src(parser_entrypoint: str, wrapper_header_path: str) -> str:
  return MAIN_WRAPPER_SRC.format(parser_entrypoint=parser_entrypoint, wrapper_header_path=wrapper_header_path)

def get_error_handler_src(callback_name: str) -> str:
    return ERROR_HANDLER_SRC.format(callback_name=callback_name)

def get_parser_entrypoint(code: str) -> str | None:
    m = re.search(r"entrypoint\s*typedef struct (?P<id>\w*).*{", code, re.DOTALL)
    if m is None:
        return None
    entrypoint = m.group("id")
    return entrypoint

def get_C_entrypoint_from_3d(filename: str, grammar_entrypoint: str) -> str:
    normalized_filename = normalize_identifier(filename)
    normalized_entrypoint = normalize_identifier(grammar_entrypoint)
    return f"{normalized_filename}Check{normalized_entrypoint}"

def get_error_callback_name(filename: str) -> str:
    return f"{filename}EverParseError"

def write_error_handler(file: Path, out: Path):
    callback_name = get_error_callback_name(file.stem)
    error_handler_src = get_error_handler_src(callback_name)
    out.write_text(error_handler_src)

def write_main(file: Path, out: Path):
    grammar_code = file.read_text()
    grammar_entrypoint = get_parser_entrypoint(grammar_code)
    if grammar_entrypoint is None:
        raise RuntimeError(f"Could not determine 3D entrypoint for grammar '{file}'.")

    parser_entrypoint = get_C_entrypoint_from_3d(file.stem, grammar_entrypoint)
    wrapper_header_path = f"{file.stem}Wrapper.h"
    main_src = get_main_src(parser_entrypoint, wrapper_header_path)
    out.write_text(main_src)
